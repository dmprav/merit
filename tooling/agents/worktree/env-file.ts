import { readFileSync } from "node:fs";
import { join } from "node:path";
import { parseEnv } from "node:util";

import { DEFAULT_COMPOSE_DATABASE_URL } from "../../scripts/local-postgres.ts";
import { getErrnoCode } from "../file-lock.ts";
import { WORKTREE_PORT_KEYS, type WorktreePorts } from "./ports.ts";

export const formatWorktreeEnvFile = ({
  slug,
  databaseUrl,
  testDatabaseUrl = DEFAULT_COMPOSE_DATABASE_URL,
  ports,
}: {
  slug: string;
  databaseUrl: string;
  testDatabaseUrl?: string;
  ports: WorktreePorts;
}): string =>
  [
    `# Generated by \`vp run worktree:create ${slug}\` — do not commit.`,
    `DATABASE_URL=${databaseUrl}`,
    `TEST_DATABASE_URL=${testDatabaseUrl}`,
    ...WORKTREE_PORT_KEYS.map((key) => `${key}=${ports[key]}`),
    "",
  ].join("\n");

const readEnvFile = (envFile: string): Record<string, string | undefined> => {
  try {
    return parseEnv(readFileSync(envFile, "utf8"));
  } catch (error) {
    const code = getErrnoCode(error);
    if (code === "ENOENT" || code === "ENOTDIR") {
      return {};
    }
    throw error;
  }
};

const isPortNumber = (port: number): boolean => Number.isInteger(port) && port > 0 && port <= 65535;

/**
 * Reads the ports a checkout's idle servers will use from the `.env.local` files they load
 * (`app/.env.local` and the root `.env.local`), so new worktrees never claim them.
 */
export const readConfiguredPorts = (checkoutRoot: string): number[] =>
  [join(checkoutRoot, "app", ".env.local"), join(checkoutRoot, ".env.local")].flatMap((envFile) => {
    const values = readEnvFile(envFile);
    return WORKTREE_PORT_KEYS.map((key) => Number(values[key])).filter(isPortNumber);
  });
