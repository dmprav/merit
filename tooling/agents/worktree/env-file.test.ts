import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { expect, test } from "vite-plus/test";

import {
  buildLocalDatabaseUrl,
  DEFAULT_COMPOSE_DATABASE_URL,
} from "../../scripts/local-postgres.ts";
import { formatWorktreeEnvFile, readConfiguredPorts } from "./env-file.ts";
import { WORKTREE_PORT_BASES } from "./ports.ts";
import { makeTempDir, useWorktreeFixtures } from "./tests/fixtures.ts";

useWorktreeFixtures();

test("formats .env.local with DATABASE_URL, TEST_DATABASE_URL, and all allocated ports", () => {
  const databaseUrl = buildLocalDatabaseUrl("merit_alpha");

  expect(formatWorktreeEnvFile({ slug: "alpha", databaseUrl, ports: WORKTREE_PORT_BASES })).toBe(
    [
      "# Generated by `vp run worktree:create alpha` — do not commit.",
      `DATABASE_URL=${databaseUrl}`,
      `TEST_DATABASE_URL=${DEFAULT_COMPOSE_DATABASE_URL}`,
      "MERIT_DEV_PORT=3100",
      "MERIT_APP_PORT=3101",
      "MERIT_WORKSPACE_PORT=3102",
      "MERIT_STORYBOOK_DEV_PORT=6106",
      "MERIT_STORYBOOK_PORT=6107",
      "",
    ].join("\n"),
  );
});

test("reads valid port settings from app/.env.local and .env.local", () => {
  const checkout = makeTempDir("merit-env-");
  mkdirSync(join(checkout, "app"), { recursive: true });
  writeFileSync(
    join(checkout, "app/.env.local"),
    "MERIT_DEV_PORT=3100\nMERIT_APP_PORT=not-a-port\nOTHER_PORT=9999\n",
    "utf8",
  );
  writeFileSync(
    join(checkout, ".env.local"),
    "MERIT_STORYBOOK_PORT=6117\nMERIT_APP_PORT=70000\n",
    "utf8",
  );

  expect(readConfiguredPorts(checkout)).toEqual([3100, 6117]);
});

test("reads no ports from a checkout without .env.local files", () => {
  expect(readConfiguredPorts(makeTempDir("merit-env-"))).toEqual([]);
  expect(readConfiguredPorts(join(makeTempDir("merit-env-"), "missing"))).toEqual([]);
});
